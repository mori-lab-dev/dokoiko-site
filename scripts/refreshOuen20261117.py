def block(slug):
    s = next(i for i, l in enumerate(L) if l == f"    slug: '{slug}',")
    e = next((i for i, l in enumerate(L) if i > s and l.startswith("    slug: '")), len(L)); return s, e
def find(slug, key, val):
    s, e = block(slug)
    for i in range(s, e):
        if re.match(rf"\s+{key}: (['\"]){re.escape(val)}\1,", L[i]): return i
    raise Exception((slug, val))
def field(i, name):
    ind = re.match(r'\s*', L[i]).group(0)
    for k in range(i + 1, i + 8):
        if L[k].startswith(f'{ind}{name}: '): return k
    raise Exception(('nofield', i, name))
def q(s): return json.dumps(s, ensure_ascii=False)
def item(slug, val, body=None, key='name', sub=None):
    """body を丸ごと差し替える／sub=(旧,新) で一部を置換する。確認日は 11/17 に。"""
    i = find(slug, key, val); b = field(i, 'body'); c = field(i, 'checked'); ind = re.match(r'\s*', L[b]).group(0)
    old = L[b]
    if body is not None: L[b] = f'{ind}body: {q(body)},'
    if sub:
        assert sub[0] in L[b], (slug, val, sub[0]); L[b] = L[b].replace(sub[0], sub[1])
    L[c] = f'{ind}checked: {q(D)},'
    log.append({'slug': slug, 'item': val, 'before_body': old.strip(), 'after_body': L[b].strip(), 'checked_after': D})
