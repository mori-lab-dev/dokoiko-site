export const NUMC = '[0-9０-９][0-9０-９,，.．]*';
export const RULES = [
  ['料金', new RegExp(`料金|入館料|拝観料|入場料|参拝料|観覧料|運賃|乗船料|宿泊料|利用料|レンタル料|${NUMC}\\s*円|無料|有料`)],
  ['休館日', /休館|定休|休業|休園|[月火水木金土日]曜(日)?(休|定休)|年中無休|無休|休み/],
  ['営業時間', new RegExp(`営業時間|開館時間|開園時間|拝観時間|参拝時間|見学時間|受付時間|営業:|営業：|${NUMC}:${NUMC}\\s*[〜～~\\-－]|${NUMC}時\\s*[〜～~]\\s*${NUMC}時`)],
  ['時刻', new RegExp(`${NUMC}:[0-9０-９]{2}|(^|[^0-9０-９])[0-9０-９]{1,2}時(?![間])(\\s*[0-9０-９]{1,2}分)?`)],
  ['標高・距離', new RegExp(`標高|海抜|${NUMC}\\s*(km|ｋｍ|㎞|キロメートル|キロ|m|ｍ|メートル|センチ|cm)(?![a-zA-Z])|全長|周囲|幹周|高さ|深さ|落差`)],
  ['年号', new RegExp(`樹齢|創建|築造|建立|造営|開創|開山|築城|開基|建築|${NUMC}\\s*年(?!間)|(慶長|元和|寛永|享保|宝永|天正|文久|嘉永|安政|明治|大正|昭和|平成|令和|延喜|大同|建久|寛政|天保)[0-9０-９元]+年|[0-9０-９]+世紀`)],
  ['その他の数値', new RegExp(`${NUMC}\\s*(段|本|人|棟|室|軒|か所|ヶ所|カ所|箇所|万|%|％|度|℃|倍|頭|匹|基|周|回|世帯|枚|ha|ヘクタール|㎡|㎢|平方|席|台|個|種|組|名|体|品)`)],
];
export const sents = (t) => String(t || '').split(/\n+/).flatMap((l) => (/^■|^[^。]{1,12}：/.test(l.trim()) && !l.includes('。') ? [l.trim()] : (l.match(/[^。]+。?/g) || []).map((x) => x.trim()))).filter(Boolean);
export const kindOf = (s) => { for (const [k, re] of RULES) if (re.test(s)) return k; return null; };

// ---- 体験談・行程案の分類（R1 の対象から外す）
export const EXP_END = /(た|だった|でした|ました|かった|った|んだ|なかった)。?$/;
const EXP_WORD = /思う|思った|感じ|気がし|したい|行きたい|ほしい|欲しい|おすすめ|オススメ|最高|最高だ|好き|驚|べきだ|べき。|ほうがいい|方がいい|といい|がいい|たほうが|てほしい|ことだ。|いいだろう|だと思|かもしれ|がち|ような気|落ち着く|おいしい|美味し|楽しめる|楽しい|圧巻|絶景|癒|静か|空いて|混んで|混む|にぎわ|賑わ|ずっと|ぎゅうぎゅう|行ってみ|行くと|着いた|訪れ|見かけ|歩い|泊ま|食べ|飲ん|入っ|浸かっ|乗っ|来た|来ると/;
const ADVICE = /こと。?$|ください。?$|を。?$|ておく|しておこう|しよう|ほうが|方が|と安心|がおすすめ|が無難|が確実|必須|必ず/;
export function isExperience(s, where) {
  if (where.type === 'info' || where.type === 'spot') return false;   // info の行・見どころの説明は事実の記述
  if (where.type === 'modelCourse') return true;                       // 行程案
  if (EXP_END.test(s)) return true;                                    // 過去形の文末（体験談）
  if (EXP_WORD.test(s)) return true;                                   // 感想・おすすめ・個人の行動
  if (ADVICE.test(s) && !/[0-9０-９]/.test(s.replace(/[0-9０-９]+(円|時|:)/g, ''))) return false;
  return false;
}

