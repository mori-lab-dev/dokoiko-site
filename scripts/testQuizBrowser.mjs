// 診断の手元確認（2026-11-17）: ビルド済みの /quiz/ をブラウザで動かして、最後まで答える・のこりが減る・共有URL・スマホ幅を確かめる。
// usage: node scripts/testQuizBrowser.mjs [http://127.0.0.1:4399]   （先に astro preview を起動しておく）
import { chromium } from 'playwright';
import fs from 'fs';
const BASE = process.argv[2] || 'http://127.0.0.1:4399';
const OUT = 'logs/quiz_20261117';
const res = [];
const ok = (name, cond, extra = '') => { res.push({ name, ok: !!cond, extra }); console.log((cond ? 'OK  ' : 'NG  ') + name + ' ' + extra); };
const browser = await chromium.launch();
for (const vp of [{ n: 'phone390', w: 390, h: 844 }, { n: 'phone360', w: 360, h: 740 }, { n: 'pc1280', w: 1280, h: 800 }]) {
  const ctx = await browser.newContext({ viewport: { width: vp.w, height: vp.h } });
  const page = await ctx.newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push(String(e)));
  page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  await page.addInitScript(() => { window.dataLayer = []; });
  const reqs = [];
  page.on('request', (r) => reqs.push(r.method() + ' ' + r.url()));
  await page.goto(BASE + '/quiz/', { waitUntil: 'networkidle' });
  const overflow = () => page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
  ok(vp.n + ' 開始画面 横スクロールなし', (await overflow()) <= 0, '差=' + (await overflow()));
  await page.screenshot({ path: OUT + '/shot_' + vp.n + '_1_intro.png' });
  await page.click('#qz-start');
  const lefts = [];
  const readLeft = async () => Number((await page.textContent('#qz-left')).replace(/,/g, ''));
  lefts.push(await readLeft());
  const picks = [1, 6, 0, 2, 0, 0, 0, 1, 0, 1, 0, 1];
  for (let i = 0; i < 12; i++) {
    const q = await page.textContent('#qz-q');
    const step = await page.textContent('#qz-step');
    const opts = await page.$$('#qz-opts .qz-opt');
    const idx = Math.min(picks[i], opts.length - 1);
    if (i === 2 && vp.n === 'phone390') await page.screenshot({ path: OUT + '/shot_' + vp.n + '_2_question.png' });
    if (i === 0) ok(vp.n + ' 質問1の見出し・ステップ', q.includes('旅の長さ') && step.includes('1 / 12'), q + ' / ' + step);
    await opts[idx].click();
    if (i < 11) lefts.push(await readLeft());
    if (i === 2) { const ov = await overflow(); ok(vp.n + ' 質問画面 横スクロールなし', ov <= 0, '差=' + ov); }
  }
  await page.waitForSelector('#qz-result:not([hidden])');
  ok(vp.n + ' 最後まで答えると結果が出る', true);
  ok(vp.n + ' のこりが減る', lefts.every((v, i) => i === 0 || v <= lefts[i - 1]) && lefts[lefts.length - 1] < lefts[0], lefts.join('→'));
  const name = await page.textContent('#qz-r-name');
  const pref = await page.textContent('#qz-r-pref');
  const link = await page.getAttribute('#qz-r-link', 'href');
  const share = await page.getAttribute('#qz-share', 'href');
  const nexts = await page.$$eval('#qz-r-next a', (as) => as.map((a) => a.getAttribute('href')));
  ok(vp.n + ' 結果: 旅先1つ＋次点3つ', name && nexts.length === 3, name + '(' + pref + ') / 次点' + nexts.length);
  ok(vp.n + ' 結果の文言「回答の傾向から選んだ1つ。ほかの候補もどうぞ」', (await page.textContent('#qz-result')).includes('回答の傾向から選んだ1つ。ほかの候補もどうぞ'));
  ok(vp.n + ' 旅先ページへのリンク（utm なし）', link.startsWith('/destinations/') && !link.includes('utm_') && nexts.every((h) => h.startsWith('/destinations/') && !h.includes('utm_')), link);
  const u = new URL(share);
  const entry = new URL(u.searchParams.get('url'));
  const id = entry.searchParams.get('utm_content');
  ok(vp.n + ' 共有: x.com/intent/post', u.origin + u.pathname === 'https://x.com/intent/post');
  ok(vp.n + ' 共有: 本文', u.searchParams.get('text') === '私に似合う旅先は【' + name + '(' + pref + ')】でした。あなたは？', u.searchParams.get('text'));
  ok(vp.n + ' 共有: url は /quiz/ ＋ utm 4つ', entry.origin + entry.pathname === 'https://tabidokoiko.com/quiz/' && entry.searchParams.get('utm_source') === 'x' && entry.searchParams.get('utm_medium') === 'social' && entry.searchParams.get('utm_campaign') === 'quiz_travelmatch_2611' && !!id && [...entry.searchParams.keys()].length === 4, entry.href);
  ok(vp.n + ' 共有: hashtags', u.searchParams.get('hashtags') === '似合う旅先,どこ行こ', u.searchParams.get('hashtags') + ' / 生のURL: ' + share.slice(share.indexOf('hashtags')));
  ok(vp.n + ' 共有: 結果は url のパス・クエリに入っていない（旅先IDは utm_content だけ）', !entry.pathname.includes(name) && ![...entry.searchParams.keys()].some((k) => !k.startsWith('utm_')));
  ok(vp.n + ' 結果画面 横スクロールなし', (await overflow()) <= 0, '差=' + (await overflow()));
  await page.screenshot({ path: OUT + '/shot_' + vp.n + '_3_result.png', fullPage: true });
  const ev = await page.evaluate(() => window.dataLayer.map((a) => Array.from(a)).filter((a) => a[0] === 'event'));
  const names = ev.map((e) => e[1]);
  ok(vp.n + ' GA4: quiz_start・quiz_complete', names.includes('quiz_start') && names.includes('quiz_complete'), names.join(','));
  await page.evaluate(() => { for (const id of ['qz-share', 'qz-r-link']) document.getElementById(id).addEventListener('click', (e) => e.preventDefault(), true); });
  await page.click('#qz-share');
  await page.click('#qz-r-link');
  const ev2 = await page.evaluate(() => window.dataLayer.map((a) => Array.from(a)).filter((a) => a[0] === 'event'));
  const sc = ev2.find((e) => e[1] === 'share_click');
  const rd = ev2.find((e) => e[1] === 'result_to_destination');
  ok(vp.n + ' GA4: share_click・result_to_destination は旅先IDだけ', sc && rd && Object.keys(sc[2]).join() === 'destination_id' && Object.keys(rd[2]).join() === 'destination_id' && sc[2].destination_id === id, JSON.stringify([sc && sc[2], rd && rd[2]]));
  ok(vp.n + ' GA4: 回答の文言を送っていない', !/静かなところ|どちらでも|1泊で|にぎやか|たくさん歩きたい/.test(JSON.stringify(ev2)));
  const stor = await page.evaluate(() => ({ ls: Object.keys(localStorage).length, ss: Object.keys(sessionStorage).length }));
  ok(vp.n + ' 保存なし（localStorage・sessionStorage）', stor.ls === 0 && stor.ss === 0, JSON.stringify(stor));
  const posts = reqs.filter((r) => r.startsWith('POST ') && !/google|doubleclick|analytics|gtag/.test(r));
  ok(vp.n + ' 診断のための送信（POST）なし', posts.length === 0, posts.join(' | '));
  ok(vp.n + ' ブラウザのエラーなし', errors.length === 0, errors.slice(0, 2).join(' | '));
  await page.click('#qz-again');
  await page.click('#qz-start');
  await page.click('#qz-opts .qz-opt >> nth=0');
  await page.click('#qz-opts .qz-opt >> nth=0');
  const before = await page.textContent('#qz-step');
  await page.click('#qz-back');
  const after = await page.textContent('#qz-step');
  ok(vp.n + ' 「ひとつ前の質問にもどる」', before.includes('3 / 12') && after.includes('2 / 12'), before + '→' + after);
  await ctx.close();
}
await browser.close();
fs.writeFileSync(OUT + '/browser_test_result.json', JSON.stringify(res, null, 1));
const ng = res.filter((r) => !r.ok);
console.log('\n' + (res.length - ng.length) + '/' + res.length + ' OK');
process.exit(ng.length ? 1 : 0);
