const data = JSON.parse(fs.readFileSync(FILES[0], 'utf8'));
const byId = new Map(data.map((d) => [d.id, d]));

let ng = 0, changed = 0, imgDropped = 0;
const log = [];
for (const [id, list] of Object.entries(FIXES)) {
  const d = byId.get(id);
  if (!d) { console.log(`❌ ${id} が見つからない`); ng++; continue; }
  for (const f of list) {
    const s = d.spots?.[f.idx];
    if (!s || s.name !== f.was) {
      console.log(`❌ ${id}[${f.idx}] が「${f.was}」ではない（実際は「${s?.name}」）`); ng++; continue;
    }
    if (f.desc.length < 30 || f.desc.length > 80) {
      console.log(`❌ ${id}[${f.idx}] 説明が${f.desc.length}字（30〜80字）`); ng++; continue;
    }
    const hadImg = Boolean(s.imageUrl);
    if (hadImg) imgDropped++;
    log.push({ id, idx: f.idx, from: f.was, to: f.name, hadImage: hadImg, src: f.src });
    d.spots[f.idx] = { name: f.name, description: f.desc };
    changed++;
    console.log(`OK  ${id.padEnd(26)}[${f.idx}] ${f.was.slice(0, 16).padEnd(18)} → ${f.name}`);
  }
}
if (ng) { console.log(`\nNG ${ng}件。1件でも合わなければ反映しない`); process.exit(1); }

console.log(`\n差し替え ${changed}件 / うち画像も外した ${imgDropped}件`);
if (APPLY) {
  const json = JSON.stringify(data, null, 2) + '\n';
  for (const f of FILES) fs.writeFileSync(f, json);
  fs.writeFileSync('logs/generated_spot_fixes.json', JSON.stringify(log, null, 1));
  console.log('✅ destinations.json を更新 / 根拠は logs/generated_spot_fixes.json');
} else {
  console.log('（--apply で反映）');
}
