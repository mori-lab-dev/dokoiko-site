export type Scheme = {
  slug: string;            // /{slug}/ で特設ページを作る
  pref: string;            // destinations.json の prefecture と同じ表記
  prefShort: string;       // 見出し用
  name: string;            // 制度の正式名称
  parent: string | null;   // 親制度（県独自ならnull）
  period: string;          // 対象期間
  booking: string;         // 予約開始
  status: 'open' | 'soon' | 'ended'; // open=予約開始済み / soon=開始日が公表済みでこれから / ended=終了（ページは残して終了を明記する）
  /**
   * 予約開始日・終了日（JST の YYYY-MM-DD）。静的HTMLは status のまま出し、ブラウザが今日の日付で
   * 『まもなく→受付中』『受付中→終了』のバッジを進める（ビルドし直さなくても、日付をまたいで古い表示にならないように）。
   * 終了を受付中に戻すことはしない。
   */
  startsOn?: string;
  endsOn?: string;
  /** 受付状況の要点（確認日時点）。販売先ごとの完売・停止・再開など、予約する前に知っておきたいこと。 */
  state?: string;
  /** この制度の情報を公式サイトで取り直した日 */
  checked: string;
  official: { label: string; url: string }[];
  note?: string;
  /** 申し込みが公式サイト経由に限られる場合の案内。宿カードの下に出す。 */
  applyNote?: string;
  /** 親制度とは別枠で触れておきたいこと（県独自キャンペーンの場合など） */
  aside?: { title: string; body: string };
  /**
   * そのページ専用のシェア画像。県の風景を使ったほうが投稿で目を引くため。
   * 用意していない県は既定の share_default.jpg になる。
   */
  share?: string;
};

